import { createHash } from "node:crypto";
import { z } from "zod";
import type { FastifyInstance } from "fastify";
import type { Database, Sql } from "./db.js";
import { requireThat } from "../../../packages/domain/src/index.js";
import { AWARD_LABELS, computeAwards } from "./awards.js";

// OJ-039 event album export: a reviewable, sequenced package manifest with
// credits, AI/rights metadata and checksums. Audio stays in private storage
// and is referenced by content hash and the authenticated performer audio
// route; nothing is submitted to any distributor automatically.
export const EXPORT_FORMAT = "our-jam-event-album/v1";

function csvCell(value: unknown) {
  const s = String(value ?? "");
  // Neutralize spreadsheet formulas as well as quoting.
  const safe = /^[=+\-@\t\r]/.test(s) ? "'" + s : s;
  return '"' + safe.replaceAll('"', '""') + '"';
}

export async function eventAlbumPackage(db: Sql, artistId: string, eventId: string, mediaConfigured: boolean) {
  const event = (
    await db.query("SELECT id,slug,title,artist_name,state,created_at FROM events WHERE id=$1 AND artist_id=$2", [eventId, artistId])
  ).rows[0];
  requireThat(event, "not_found", "Event not found.", 404);
  const rows = (
    await db.query(
      `SELECT rel.id,rel.title,rel.duration_seconds,rel.published_at,rel.asset_sha256,rel.provenance,
        j.provider,j.model,j.prompt_hash,j.snapshot,r.opened_at,COALESCE(r.closed_at,j.created_at) closed_at,
        s.title source_title,s.ordinal source_ordinal
       FROM releases rel JOIN generation_jobs j ON j.id=rel.job_id JOIN rounds r ON r.id=j.round_id
       JOIN source_tracks s ON s.id=r.source_id
       WHERE rel.event_id=$1 AND rel.published_at IS NOT NULL AND NOT rel.hidden
       ORDER BY rel.published_at,rel.id`,
      [eventId],
    )
  ).rows;
  const authorIds = new Set<string>();
  for (const r of rows) for (const w of r.snapshot?.selected ?? []) authorIds.add(w.authorId);
  const people = new Map(
    (
      await db.query("SELECT id,name,anonymous FROM participants WHERE id=ANY($1::uuid[])", [[...authorIds]])
    ).rows.map((p) => [p.id, p.anonymous ? "Anonymous fan" : p.name]),
  );
  const tracks = rows.map((r, i) => {
    const { awards } = computeAwards(r.snapshot ?? {}, new Date(r.opened_at), new Date(r.closed_at));
    return {
      position: i + 1,
      releaseId: r.id,
      title: r.title,
      durationSeconds: Number(r.duration_seconds),
      publishedAt: new Date(r.published_at).toISOString(),
      basedOn: { sourceTrack: r.source_title, albumPosition: r.source_ordinal },
      audio: {
        sha256: r.asset_sha256 ?? null,
        performerDownload: "/api/operator/releases/" + r.id + "/audio",
        available: mediaConfigured && Boolean(r.asset_sha256),
      },
      ai: {
        generated: true,
        provider: r.provider ?? r.provenance?.provider ?? null,
        model: r.model ?? r.provenance?.model ?? null,
        promptSha256: r.prompt_hash,
        disclosure: "Audio generated by an AI music model from the artist's private core prompt and audience Sound Waves.",
      },
      credits: (r.snapshot?.selected ?? []).map((w: any, rank: number) => ({
        rank: rank + 1,
        soundWave: w.text,
        contributor: people.get(w.authorId) ?? "Anonymous fan",
        votes: w.votes,
      })),
      awards: awards.map((a) => ({ label: AWARD_LABELS[a.kind], soundWave: a.text })),
    };
  });
  const body = {
    format: EXPORT_FORMAT,
    generatedAt: new Date().toISOString(),
    event: {
      id: event.id,
      slug: event.slug,
      title: event.title,
      artist: event.artist_name,
      state: event.state,
      createdAt: new Date(event.created_at).toISOString(),
    },
    review: {
      status: "draft_for_artist_review",
      distributorDelivery: "manual",
      notes: [
        "Review titles, artwork, credits and rights before submitting to any distributor.",
        "Distributor delivery is never instantaneous and is not automated by Our Jam.",
        "Private core prompts are excluded; only their SHA-256 is recorded.",
        ...(mediaConfigured ? [] : ["Private media storage is not configured, so audio files are not downloadable from this server."]),
      ],
    },
    rights: {
      aiGenerated: true,
      fanContributionTerms: "Fans contributed short text Sound Waves; contributors are credited by display name or as anonymous.",
    },
    tracks,
  };
  const manifestSha256 = createHash("sha256").update(JSON.stringify(body)).digest("hex");
  return { ...body, manifestSha256 };
}

export function creditsCsv(pkg: Awaited<ReturnType<typeof eventAlbumPackage>>) {
  const lines = [["position", "track", "duration_seconds", "audio_sha256", "credit_rank", "sound_wave", "contributor", "votes", "ai_provider", "ai_model"].join(",")];
  for (const t of pkg.tracks)
    for (const c of t.credits.length ? t.credits : [{ rank: "", soundWave: "", contributor: "", votes: "" }])
      lines.push(
        [t.position, t.title, t.durationSeconds, t.audio.sha256 ?? "", c.rank, c.soundWave, c.contributor, c.votes, t.ai.provider ?? "", t.ai.model ?? ""]
          .map(csvCell)
          .join(","),
      );
  return lines.join("\r\n") + "\r\n";
}

export function registerEventExport(app: FastifyInstance, db: Database, mediaConfigured: boolean) {
  const session = (app as any).ojSession as (req: any, kind: "operator") => Promise<any>;
  app.get("/api/operator/events/:id/export", async (req, reply) => {
    const op = await session(req, "operator");
    const eventId = z.uuid().parse((req.params as any).id);
    const format = z.enum(["json", "csv"]).default("json").parse((req.query as any).format);
    const pkg = await eventAlbumPackage(db, op.artist_id, eventId, mediaConfigured);
    const name = "our-jam-" + pkg.event.slug.replace(/[^a-z0-9-]/gi, "") + "-album";
    if (format === "csv")
      return reply
        .type("text/csv; charset=utf-8")
        .header("Content-Disposition", `attachment; filename="${name}-credits.csv"`)
        .send(creditsCsv(pkg));
    return reply.header("Content-Disposition", `attachment; filename="${name}.json"`).send(pkg);
  });
}
